// Small deterministic PRNG (mulberry32) so a given seed always produces the
// same exploration order. This only needs to be reproducible, not
// cryptographically random, so no dependency is needed for it.

export type Rng = () => number

export function createRng(seed: number | string): Rng {
  let state = typeof seed === 'number' ? seed >>> 0 : hashSeed(seed)
  return function next(): number {
    state = (state + 0x6d2b79f5) | 0
    let t = Math.imul(state ^ (state >>> 15), 1 | state)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

function hashSeed(seed: string): number {
  let hash = 2166136261
  for (let i = 0; i < seed.length; i++) {
    hash ^= seed.charCodeAt(i)
    hash = Math.imul(hash, 16777619)
  }
  return hash >>> 0
}

// Deterministic Fisher-Yates shuffle. Does not mutate `items`.
export function shuffle<T>(items: readonly T[], rng: Rng): T[] {
  const result = [...items]
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1))
    const temp = result[i]
    result[i] = result[j]
    result[j] = temp
  }
  return result
}
